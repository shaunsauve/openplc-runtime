#!/usr/bin/env python3
"""Generate corpus:large-data's program.st (1,000 scalars are too many to hand-write).

Usage: gen.py          rewrite program.st
       gen.py --check  exit 1 if program.st differs from what this script emits

See also:
  tests/debug/corpus/build_all.sh - runs `gen.py --check` before compiling.
  tests/debug/corpus/large-data/program.st - the generated program, committed.
"""

from __future__ import annotations

import sys
from pathlib import Path

GROUPS = 100
PER_GROUP = 10
EVERY_SCAN = 64

HEADER = """(* corpus: large-data
   criteria: A069 A092 A098 A129 A195 A209
   fc: FC-TST-1 FC-ED-5 FC-IN-3 FC-IN-4 FC-IN-5 FC-IN-16 FC-SEC-8 FC-TR-10
   witness: Main PROG0.witness %QD0

   Generated by gen.py; edit that, not this file. A 10,000-element array
   (big), 1,000 scalars v0000..v0999 of which exactly 10 change per scan
   (scan k sets group (k - 1) MOD 100, i.e. v[10g .. 10g+9], to k), and 64
   scalars e00..e63 that change every scan (e_n = k + n, A209's trace set).
   big[(k - 1) MOD 10000] := k, and big[i] = i * 3 at start (paging, A092).
*)
"""


def render() -> str:
    decl = ["PROGRAM LargeData", "  VAR", "    witness AT %QD0 : DINT;", "    g : INT;", "    i : INT;",
            "    big : ARRAY[0..9999] OF DINT;"]
    decl += [f"    v{n:04d} : DINT;" for n in range(GROUPS * PER_GROUP)]
    decl += [f"    e{n:02d} : DINT;" for n in range(EVERY_SCAN)]
    decl += ["    seeded : BOOL;", "  END_VAR"]
    body = ["  witness := witness + 1;                                  (*@WITNESS*)",
            "  IF NOT seeded THEN",
            "    FOR i := 0 TO 9999 DO",
            "      big[i] := INT_TO_DINT(i) * 3;",
            "    END_FOR;",
            "    seeded := TRUE;",
            "  END_IF;",
            "  g := DINT_TO_INT((witness - 1) MOD 100);                 (*@GROUP*)",
            "  CASE g OF"]
    for grp in range(GROUPS):
        body.append(f"    {grp}:")
        body += [f"      v{grp * PER_GROUP + k:04d} := witness;" for k in range(PER_GROUP)]
    body.append("  END_CASE;")
    body += [f"  e{n:02d} := witness + {n};" for n in range(EVERY_SCAN)]
    body.append("  big[(witness - 1) MOD 10000] := witness;                 (*@LAST*)")
    config = ["END_PROGRAM", "", "CONFIGURATION Config0", "  RESOURCE Res0 ON PLC",
              "    TASK Main(INTERVAL := T#100ms, PRIORITY := 1);",
              "    PROGRAM PROG0 WITH Main : LargeData;", "  END_RESOURCE", "END_CONFIGURATION", ""]
    return HEADER + "\n" + "\n".join(decl + body + config)


def main(argv: list[str]) -> int:
    target = Path(__file__).resolve().parent / "program.st"
    text = render()
    if argv[1:] == ["--check"]:
        if target.read_text(encoding="utf-8") != text:
            print(f"{target} is stale: run {Path(__file__).name}")
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
